const SEPARATOR = " / ";

export function listProvinces(): string[] {
  return Object.keys(IRAN_PROVINCES);
}

export function listCities(province: string): string[] {
  return IRAN_PROVINCES[province] ?? [];
}

export function formatProvinceCity(province: string, city: string): string {
  const p = province.trim();
  const c = city.trim();
  if (!p || !c) return "";
  return `${p}${SEPARATOR}${c}`;
}

export function parseProvinceCity(valueRaw: string): { province: string; city: string } {
  const raw = (valueRaw ?? "").trim();
  if (!raw) return { province: "", city: "" };
  const idx = raw.indexOf(SEPARATOR);
  if (idx === -1) {
    // Legacy free-text city: try to recover if it matches a known city uniquely,
    // otherwise leave as city-only with empty province.
    for (const [province, cities] of Object.entries(IRAN_PROVINCES)) {
      if (cities.includes(raw)) return { province, city: raw };
    }
    return { province: "", city: raw };
  }
  return {
    province: raw.slice(0, idx).trim(),
    city: raw.slice(idx + SEPARATOR.length).trim(),
  };
}

export function filterLocationNames(names: string[], query: string): string[] {
  const q = query.trim();
  if (!q) return names;
  return names.filter((name) => matchesAllTerms(name, q));
}
